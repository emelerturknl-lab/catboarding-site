const fs = require('fs');
const path = require('path');

const targetDir = path.join(process.cwd(), 'Konuklarımız', 'gift');
const outputFilePath = path.join(process.cwd(), 'assets', 'js', 'automated-guests-data.js');

function generateData() {
    console.log(`\n🔍 Scanning directory: ${targetDir}`);
    
    if (!fs.existsSync(targetDir)) {
        console.error('❌ Error: Directory does not exist! Please create Konuklarımız/gift folder.');
        return;
    }

    let files;
    try {
        files = fs.readdirSync(targetDir);
    } catch (err) {
        console.error(`❌ Error reading directory: ${err.message}`);
        return;
    }

    const guests = [];
    const processedNames = new Set();
    const unsupportedFiles = [];
    const validExtensions = ['.png', '.jpg', '.jpeg', '.webp', '.gif'];
    
    // Check for unsupported files
    files.forEach(f => {
        if (f.startsWith('.') || f.endsWith('.txt') || f.endsWith('.md')) return; // Ignore system and text files
        const ext = path.extname(f).toLowerCase();
        if (!validExtensions.includes(ext) && ext !== '') {
            unsupportedFiles.push(f);
            console.log(`⚠ Warning: Unsupported file detected and ignored: ${f}`);
        }
    });

    // Find all cover photos
    const coverFiles = files.filter(f => f.toUpperCase().startsWith('KAPAK-') && validExtensions.includes(path.extname(f).toLowerCase()));
    
    if (coverFiles.length === 0) {
        console.log(`⚠ Warning: No cover images (starting with KAPAK-) found in ${targetDir}`);
    }

    coverFiles.forEach(coverFile => {
        try {
            // Extract guest name
            const match = coverFile.match(/^KAPAK-(.+?)(?:-\d+)?\.[a-zA-Z0-9]+$/i);
            if (match) {
                const guestName = match[1].trim();
                
                // Check for duplicates
                if (processedNames.has(guestName.toUpperCase())) {
                    console.log(`⚠ Warning: Duplicate cover found for guest: ${guestName}. Skipping ${coverFile}.`);
                    return;
                }
                processedNames.add(guestName.toUpperCase());
                
                // Find gallery photos
                const galleryPhotos = files.filter(f => {
                    if (f === coverFile) return false;
                    const ext = path.extname(f).toLowerCase();
                    if (!validExtensions.includes(ext)) return false;
                    return f.toUpperCase().startsWith(guestName.toUpperCase());
                });

                // Find description if exists
                let description = 'Göz alıcı zarafeti ve asil duruşuyla evimizin en özel misafirlerinden biri. Sevgi dolu ve sakin karakteriyle kalbimizde taht kurdu.'; // Premium placeholder
                const textFiles = files.filter(f => f.toUpperCase().startsWith(guestName.toUpperCase()) && (f.endsWith('.txt') || f.endsWith('.md')));
                if (textFiles.length > 0) {
                    try {
                        description = fs.readFileSync(path.join(targetDir, textFiles[0]), 'utf8');
                        console.log(`  📝 Loaded custom description for ${guestName}`);
                    } catch (e) {
                        console.error(`  ❌ Could not read description file for ${guestName}: ${e.message}`);
                    }
                }

                guests.push({
                    name: guestName,
                    cover: `/Konuklarımız/gift/${coverFile}`,
                    gallery: galleryPhotos.map(f => `/Konuklarımız/gift/${f}`),
                    description: description
                });

                console.log(`✓ Guest detected: ${guestName} | Gallery images: ${galleryPhotos.length}`);
            } else {
                 console.log(`⚠ Warning: Could not parse guest name from cover file: ${coverFile}`);
            }
        } catch (err) {
            console.error(`❌ Unexpected error processing cover file ${coverFile}: ${err.message}`);
        }
    });

    // Write to JS file
    try {
        const fileContent = `// Automatically generated by generate-guests-data.js\nconst guestsData = ${JSON.stringify(guests, null, 4)};`;
        fs.writeFileSync(outputFilePath, fileContent, 'utf8');
        console.log(`\n✨ Successfully generated data for ${guests.length} guests at ${outputFilePath}\n`);
    } catch (err) {
        console.error(`❌ Error writing output file: ${err.message}`);
    }
}

generateData();
